"""Embed text files (shaders) in a C header as string constants.

usage: embed_text.py OUT.h PREFIX FILE...

Each FILE becomes `static const char PREFIX_<name>[]`, where <name> is
the file name with every non-alphanumeric character replaced by '_'
(light.frag -> PREFIX_light_frag).
"""
import os
import re
import sys


def c_string(text: str) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        esc = line.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
        out.append(f'    "{esc}"')
    return '\n'.join(out) if out else '    ""'


def main(argv: list[str]) -> int:
    if len(argv) < 4:
        print(__doc__, file=sys.stderr)
        return 2
    out, prefix, files = argv[1], argv[2], argv[3:]
    parts = ['/* Generated by tools/embed_text.py: do not edit. */\n#pragma once\n']
    for path in files:
        name = re.sub(r'[^A-Za-z0-9]', '_', os.path.basename(path))
        with open(path, encoding='utf-8') as f:
            parts.append(f'static const char {prefix}_{name}[] =\n{c_string(f.read())};\n')
    text = '\n'.join(parts)
    try:
        with open(out, encoding='utf-8') as f:
            if f.read() == text:
                return 0   # unchanged: keep the timestamp, skip rebuilds
    except FileNotFoundError:
        pass
    with open(out, 'w', encoding='utf-8') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
