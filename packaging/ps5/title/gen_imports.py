"""port: PS5 title (docs/PS5.md): write imports.gen.h, the list of every
symbol a linked title imports, for title.c's startup import check.

usage: gen_imports.py LINKED_PIE OUT_HEADER"""
import subprocess
import sys

pie, out = sys.argv[1], sys.argv[2]
dyn = subprocess.run(['readelf', '--dyn-syms', '-W', pie], capture_output=True, text=True,
                     check=True).stdout
names = sorted({f[7] for f in (l.split() for l in dyn.splitlines())
                if len(f) >= 8 and f[6] == 'UND' and f[7] and '@' not in f[7]})
with open(out, 'w') as h:
    h.write('/* Generated by gen_imports.py: the imports of the linked title. */\n')
    h.write('#define CT_IMPORTS(X) \\\n')
    for i, n in enumerate(names):
        h.write(f'    X({i}, "{n}") \\\n')
    h.write('\n')
print(f'{len(names)} imports -> {out}')
