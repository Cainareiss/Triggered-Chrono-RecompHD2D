"""port: PS5 title (docs/PS5.md): write imports.gen.h, every symbol a linked
title imports and the system module it was linked against, for title.c's
startup import check.

usage: gen_imports.py LINKED_PIE STUB_DIR OUT_HEADER"""
import glob
import os
import subprocess
import sys

pie, stub_dir, out = sys.argv[1:4]


def names(cmd):
    return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout


dyn = names(['readelf', '--dyn-syms', '-W', pie])
imports = sorted({f[7] for f in (l.split() for l in dyn.splitlines())
                  if len(f) >= 8 and f[6] == 'UND' and f[7] and '@' not in f[7]})
needed = [l.split('[')[1].split(']')[0] for l in names(['readelf', '-dW', pie]).splitlines()
          if '(NEEDED)' in l]
# The first NEEDED module (link order) whose stub defines the symbol, as lld chose.
provider = {}
for so in needed:
    stub = os.path.join(stub_dir, so.replace('.sprx', '.so'))
    if not os.path.exists(stub):
        continue
    for line in names(['readelf', '--dyn-syms', '-W', stub]).splitlines():
        f = line.split()
        if len(f) >= 8 and f[6] != 'UND':
            provider.setdefault(f[7], so.replace('.sprx', ''))
with open(out, 'w') as h:
    h.write('/* Generated by gen_imports.py: the imports of the linked title. */\n')
    h.write('#define CT_IMPORTS(X) \\\n')
    for i, n in enumerate(imports):
        h.write(f'    X({i}, "{n}", "{provider.get(n, "?")}") \\\n')
    h.write('\n')
print(f'{len(imports)} imports from {len(needed)} modules -> {out}')
